//go:build ignore

// Generates confusables_table.go from Unicode's confusables.txt:
//
//	curl -O https://www.unicode.org/Public/security/latest/confusables.txt
//	go run gen_confusables.go confusables.txt
//
// The whole file has over 6,000 entries for scripts names can't use. This keeps
// what Skeleton can meet in a valid name, plus anything that passes for plain
// ASCII letters and digits, which Latinize needs for chat.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func usable(r rune) bool {
	return unicode.In(r, unicode.Latin, unicode.Greek, unicode.Cyrillic, unicode.Han,
		unicode.Hiragana, unicode.Katakana, unicode.Hangul, unicode.Inherited) ||
		r < unicode.MaxASCII
}

func plainASCII(s string) bool {
	for _, r := range s {
		if r >= unicode.MaxASCII || !(unicode.IsLetter(r) || unicode.IsDigit(r)) {
			return false
		}
	}
	return s != ""
}

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	date := ""
	table := map[rune]string{}
	scan := bufio.NewScanner(f)
	scan.Buffer(make([]byte, 64*1024), 64*1024)
	for scan.Scan() {
		line := scan.Text()
		if strings.HasPrefix(line, "# Date: ") {
			date = strings.TrimPrefix(line, "# Date: ")
		}
		code, _, _ := strings.Cut(line, "#")
		parts := strings.Split(code, ";")
		if len(parts) != 3 {
			continue
		}
		src, err := strconv.ParseInt(strings.TrimSpace(parts[0]), 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		var target strings.Builder
		for _, field := range strings.Fields(parts[1]) {
			cp, err := strconv.ParseInt(field, 16, 32)
			if err != nil {
				log.Fatal(err)
			}
			target.WriteRune(rune(cp))
		}
		if usable(rune(src)) || plainASCII(target.String()) {
			table[rune(src)] = target.String()
		}
	}
	if err := scan.Err(); err != nil {
		log.Fatal(err)
	}

	keys := make([]rune, 0, len(table))
	for r := range table {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen_confusables.go; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: Unicode confusables.txt, %s.\n", date)
	fmt.Fprintf(&out, "// https://www.unicode.org/terms_of_use.html\n\n")
	fmt.Fprintf(&out, "package usernames\n\nvar confusables = map[rune]string{\n")
	for _, r := range keys {
		fmt.Fprintf(&out, "0x%04X: %s,\n", r, strconv.QuoteToASCII(table[r]))
	}
	fmt.Fprintf(&out, "}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("confusables_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d entries\n", len(keys))
}
